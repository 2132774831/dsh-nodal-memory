/**
 * 系统提示词：让模型知道有这个记忆库、什么时候写、什么时候查。
 *
 * 设计原则（v1 已经验证过，继续沿用）：
 *   **任何"提醒模型做某事"的需求，优先加在常驻提示词里，不要新开消息注入。**
 *   注入消息会被写进会话历史，之后每个请求都要重发；历史上的 1.1.2 版本
 *   就因为每轮注入导致历史"滚雪球"，修了一次才干净。
 *
 * 这里是纯函数：输入配置和统计，输出文本。没有副作用，好测。
 */

import { NS } from './config.js';

export function buildBrief(ctx) {
  const { config, count, noKind, review } = ctx;
  if (!config.enabled || config.injectBrief === false) return '';

  // 定期体检提醒：只往常驻提示词里加一行，不注入消息
  const note = [];
  if (review && review.overdue) {
    note.push(
      '',
      '### ⏰ 记忆该体检了',
      review.lastReviewAt === 0
        ? '这个库还没整理过。建议主动调用 `memory_review` 看一遍（重复 / 从没用上 / 缺标签 / 没分类）。'
        : `距上次整理已 ${review.daysSince} 天（约定 ${review.interval} 天一次）。建议调用 \`memory_review\` 看一遍。`,
    );
  }

  return [
    '## 本地长期记忆（' + NS + '）',
    '',
    '这个会话接了一个**只存在本机**的长期记忆库：数据在你自己的硬盘上，默认不联网、不上传。',
    `当前已记录 ${count} 条记忆，跨对话、跨项目共享。`,
    '',
    '用法约定：',
    '- 回忆用户偏好、项目约定、历史决策、踩过的坑：`memory_search`。',
    '- 想看看都记了什么：`memory_list`；内容过时了用 `memory_forget` 删掉（软删，可恢复）。',
    '- 记忆是可能过期的历史结论：与当前代码/用户最新说法冲突时，以现状为准。',
    '- 不要记代码里一眼能看出来的东西，也不要把临时中间状态记进去。',
    '',
    '写记忆时顺手填 `kind`（work/emotion/preference）和 `importance`（key/important/casual/transient）：'
      + '你此刻就在对话里，比事后用模型去推断准得多，也不用额外花一次推理。',
    ...(noKind > 0
      ? ['', `注：库里有 ${noKind} 条记忆还没分类（多为历史迁移数据），检索命中它们时不影响使用，` +
          '若你恰好读到并了解背景，可以在下次写相关记忆时顺手补上 kind。']
      : []),
    '',
    '### 收工自检（每次干完一件重要的事，必须过一遍）',
    '',
    '只要本轮出现下面任意一种情况，就在收尾回复之前自检一次：',
    '',
    '- 改了代码 / 修了 bug / 改配置',
    '- 发布了版本、建了 release、推了远端',
    '- 安装、升级、卸载了插件或依赖',
    '- 踩到坑并找到了原因（尤其是"看着像 A 其实是 B"的那种）',
    '- 确定了项目约定、目录结构、用户偏好、或某个决策背后的理由',
    '',
    '自检问题只有一句：**这里面有没有下次还能复用、且从代码里看不出来的结论？**',
    '',
    '- **有 → 直接调用 `memory_save` 存下来，不要问用户"要不要存"。**',
    '  存的时候写成能独立读懂的一句话，带上"为什么"。',
    '- **没有 → 跳过，不要为了凑数而存。**',
    '',
    '只有「删除记忆」「改写已有记忆」这类破坏性操作才需要先问用户。',
    ...note,
  ].join('\n');
}
